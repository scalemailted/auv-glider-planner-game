export function buildSamplingProcessConsoleHandlers(scene = {}) {
  return {
    distribution: (distribution) => scene.handleSamplingDistributionChange?.(distribution),
    seed: (seed) => scene.handleSamplingSeedChange?.(seed),
    behaviorPreset: (behaviorPresetId) => scene.applyBehaviorPreset?.(behaviorPresetId),
    patternSource: (patternSource) => scene.applyPatternSource?.(patternSource),
    processMode: (processMode) => scene.applyProcessMode?.(processMode),
    paintSelection: (patch) => scene.applyPaintSelection?.(patch),
    paintSelectedCell: (patch) => scene.paintSelectedCell?.(patch),
    clearPaintCell: () => scene.clearSelectedPaintCell?.(),
    clearPaintCanvas: () => scene.clearProcessPaintCanvas?.(),
    runProcessPaint: () => scene.runProcessPaintCanvas?.(),
    exportProcessRecipe: () => scene.exportDemoJson?.(),
    randomizeProcessAllocation: (patch) => scene.randomizeProcessAllocation?.(patch),
    exampleTrack: (track) => scene.applyExampleTrack?.(track),
    processExample: (exampleId) => scene.applyReferenceSignature?.(exampleId),
    referenceSignature: (referenceSignatureId) => scene.applyReferenceSignature?.(referenceSignatureId),
    compareComponent: (comparisonId) => scene.applyComponentComparison?.(comparisonId),
    eventLikelihood: (eventLikelihood) => scene.handleSamplingEventLikelihoodChange?.(eventLikelihood),
    eventLikelihoodDynamics: (eventLikelihoodDynamics) => scene.handleSamplingEventLikelihoodDynamicsChange?.(eventLikelihoodDynamics),
    eventLikelihoodTemporalPattern: (eventLikelihoodTemporalPattern) => scene.handleSamplingEventLikelihoodTemporalPatternChange?.(eventLikelihoodTemporalPattern),
    eventLikelihoodSpatialEvolution: (eventLikelihoodSpatialEvolution) => scene.handleSamplingEventLikelihoodSpatialEvolutionChange?.(eventLikelihoodSpatialEvolution),
    hotspotCount: (hotspotCount) => scene.handleSamplingHotspotCountChange?.(hotspotCount),
    clusterSize: (clusterSize) => scene.handleSamplingClusterSizeChange?.(clusterSize),
    noise: (noise) => scene.handleSamplingNoiseChange?.(noise),
    timeMode: (timeMode) => scene.handleSamplingTimeModeChange?.(timeMode),
    spatialPattern: (spatialPattern) => scene.handleSamplingSpatialPatternChange?.(spatialPattern),
    valueDistribution: (valueDistribution) => scene.handleSamplingValueDistributionChange?.(valueDistribution),
    temporalPattern: (temporalPattern) => scene.handleSamplingTemporalPatternChange?.(temporalPattern),
    temporalBehavior: (temporalBehavior) => scene.handleSamplingTemporalBehaviorChange?.(temporalBehavior),
    evolutionModel: (evolutionModel) => scene.handleSamplingEvolutionModelChange?.(evolutionModel),
    patternEvolution: (patternEvolution) => scene.handleSamplingPatternEvolutionChange?.(patternEvolution),
    spatialEvolution: (spatialEvolution) => scene.handleSamplingSpatialEvolutionChange?.(spatialEvolution),
    motionScope: (motionScope) => scene.handleSamplingMotionScopeChange?.(motionScope),
    interactionScale: (interactionScale) => scene.handleSamplingInteractionScaleChange?.(interactionScale),
    stateModel: (stateModel) => scene.handleSamplingStateModelChange?.(stateModel),
    dynamicComplexity: (dynamicComplexity) => scene.handleSamplingDynamicComplexityChange?.(dynamicComplexity),
    depletionMode: (depletionMode) => scene.handleSamplingDepletionModeChange?.(depletionMode),
    displayMode: (displayMode) => scene.handleSamplingDisplayModeChange?.(displayMode),
    viewFilters: (patch) => scene.applyViewFilters?.(patch),
    timeSpeedScale: (timeSpeedScale) => scene.handleSamplingTimeSpeedScaleChange?.(timeSpeedScale),
    tickRate: (tickRate) => scene.handleProcessTickRateChange?.(tickRate),
    stepGeneration: () => scene.stepProcessGeneration?.({ render: true, updateUi: true }),
    behaviorHelp: (groupId) => scene.showBehaviorHelp?.(groupId),
    regenerate: () => scene.handleSamplingRegenerate?.(),
    pause: () => scene.handleSamplingPause?.(),
    direction: () => scene.togglePlaybackDirection?.(),
    reset: () => scene.resetDemoState?.(),
    exportSettings: (patch) => scene.updateExportSettings?.(patch),
    scenarioSettings: (patch, options) => scene.updateScenarioSettings?.(patch, options),
    generateScenario: () => scene.generateScenario?.(),
    exportDemoJson: () => scene.exportDemoJson?.(),
    exportScenarioJson: () => scene.exportScenarioJson?.(),
    menu: () => scene.handleSamplingMainMenu?.()
  };
}
